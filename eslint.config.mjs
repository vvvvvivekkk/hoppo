import js from '@eslint/js';
import tseslint from 'typescript-eslint';

/**
 * Lint configuration for the TypeScript packages and the API.
 *
 * One flat config at the root rather than one per package. ESLint 9 dropped
 * `.eslintrc` support by default, which is why the `lint` scripts in
 * `packages/shared`, `packages/api-client` and `apps/api` had never actually
 * run — each exited 2 with "couldn't find an eslint.config.js" before linting
 * a single file. A script that cannot run is worse than no script, because it
 * reads as coverage that is not there.
 *
 * The Next.js apps are not covered here. `next lint` reads their own
 * `.eslintrc.json` through its compatibility layer and adds the rules that
 * only make sense for a Next app, so duplicating them here would mean two
 * sources of truth for the same files.
 *
 * Type-aware linting (`recommendedTypeChecked`) is deliberately not enabled.
 * It needs a program per package and roughly triples the run time, and the
 * rules it adds overlap heavily with what `tsc --noEmit` already catches in
 * `pnpm typecheck`. The rules below are the ones type-checking does *not*
 * give us.
 */
export default tseslint.config(
  {
    ignores: [
      '**/dist/**',
      '**/.next/**',
      '**/node_modules/**',
      // Generated by Prisma, and not ours to style.
      'apps/api/src/generated/**',
    ],
  },

  js.configs.recommended,
  ...tseslint.configs.recommended,

  {
    rules: {
      // An unused variable is usually a leftover from a refactor. The
      // underscore escape hatch is for the genuine cases: a required
      // positional parameter, or a destructure that drops a field.
      '@typescript-eslint/no-unused-vars': [
        'error',
        { argsIgnorePattern: '^_', varsIgnorePattern: '^_', caughtErrors: 'none' },
      ],

      // `any` turns off the thing we are paying for by using TypeScript. A
      // warning rather than an error because `--max-warnings 0` already makes
      // it fail the build, and a warning prints better in an editor.
      '@typescript-eslint/no-explicit-any': 'warn',

      // Nest's DI relies on parameter properties and decorator metadata, and
      // Prisma's generated types produce plenty of empty interfaces.
      '@typescript-eslint/no-empty-object-type': 'off',

      // `require` has a legitimate use in a CommonJS config file.
      '@typescript-eslint/no-require-imports': 'off',

      eqeqeq: ['error', 'always', { null: 'ignore' }],
      'no-console': 'off',
    },
  },

  {
    // Specs assert on shapes that are deliberately wrong, so the strictness
    // that helps in source code gets in the way here.
    files: ['**/*.spec.ts', '**/*.test.ts', '**/test/**/*.ts'],
    rules: {
      '@typescript-eslint/no-explicit-any': 'off',
      '@typescript-eslint/no-non-null-assertion': 'off',
    },
  },
);
